export type TranslationKey = keyof typeof translations.en

export function detectBrowserLanguage(): Language {
  const browserLang = navigator.language?.toLowerCase() || ''
  if (browserLang.startsWith('sv')) return 'sv'
  return 'en'
}

export function getStoredLanguage(): Language {
  try {
    const stored = localStorage.getItem('jobtrack_language')
    if (stored === 'en' || stored === 'sv') return stored
  } catch {}
  return detectBrowserLanguage()
}

export function setStoredLanguage(lang: Language): void {
  try {
    localStorage.setItem('jobtrack_language', lang)
  } catch {}
}

export function t(key: TranslationKey, lang: Language, vars?: Record<string, string | number>): string {
  let text = (translations[lang] as any)[key] ?? (translations.en as any)[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(`{${k}}`, String(v))
    }
  }
  return text
}
